-- Supabase Schema for TeleFlow / Crypto Bot Copier
-- Run this SQL in your Supabase SQL Editor (Dashboard -> SQL Editor -> New Query)

-- 1. Settings Table
CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT
);

-- 2. Workflows Table
CREATE TABLE IF NOT EXISTS workflows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    source_channel TEXT,
    source_channel_id TEXT,
    target_channel TEXT,
    target_channel_id TEXT,
    is_active BOOLEAN DEFAULT TRUE
);

-- 3. Rules Table
CREATE TABLE IF NOT EXISTS rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id BIGINT REFERENCES workflows(id) ON DELETE CASCADE,
    rule_type TEXT,
    search_text TEXT,
    replace_text TEXT,
    time_min TEXT,
    time_max TEXT
);

-- 4. CTO Signals Table
CREATE TABLE IF NOT EXISTS cto_signals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ca TEXT,
    name TEXT,
    platform TEXT,
    market_cap TEXT,
    age TEXT,
    migration_age TEXT,
    perf_5m REAL,
    perf_1h REAL,
    perf_6h REAL,
    perf_24h REAL,
    liquidity_usd REAL,
    volume_5m REAL,
    volume_1h REAL,
    volume_6h REAL,
    volume_24h REAL,
    status TEXT,
    dex_url TEXT,
    migration_status TEXT,
    workflow_id BIGINT,
    signal_type TEXT DEFAULT 'approved',
    payment_timestamp BIGINT,
    order_status TEXT,
    reason TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Published Dexscreener events, kept separate from SOL-payment/CTO signals.
CREATE TABLE IF NOT EXISTS dex_validated (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ca TEXT,
    name TEXT,
    platform TEXT,
    market_cap TEXT,
    age TEXT,
    perf_5m REAL,
    perf_1h REAL,
    perf_6h REAL,
    perf_24h REAL,
    liquidity_usd REAL,
    volume_5m REAL,
    volume_1h REAL,
    volume_6h REAL,
    volume_24h REAL,
    status TEXT,
    dex_url TEXT,
    migration_status TEXT,
    workflow_id BIGINT,
    signal_type TEXT,
    payment_timestamp BIGINT,
    order_status TEXT,
    published_at BIGINT,
    fetched_at BIGINT,
    detection_seconds REAL,
    reason TEXT,
    formatted_message TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (ca, signal_type, payment_timestamp, order_status)
);
ALTER TABLE dex_validated ADD COLUMN IF NOT EXISTS formatted_message TEXT;

-- 5. Wallet Payments Table (Enriched with token & performance details)
CREATE TABLE IF NOT EXISTS wallet_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracked_address TEXT,
    sender_address TEXT,
    amount REAL,
    mint TEXT,
    signature TEXT UNIQUE,
    timestamp BIGINT,
    token_name TEXT,
    ca TEXT,
    platform TEXT,
    market_cap TEXT,
    age TEXT,
    migration_age TEXT,
    perf_5m REAL,
    perf_1h REAL,
    perf_6h REAL,
    perf_24h REAL,
    liquidity_usd REAL,
    volume_5m REAL,
    volume_1h REAL,
    volume_6h REAL,
    volume_24h REAL,
    dex_url TEXT,
    migration_status TEXT,
    status TEXT,
    reason TEXT,
    formatted_message TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE cto_signals ADD COLUMN IF NOT EXISTS liquidity_usd REAL;
ALTER TABLE cto_signals ADD COLUMN IF NOT EXISTS volume_5m REAL;
ALTER TABLE cto_signals ADD COLUMN IF NOT EXISTS volume_1h REAL;
ALTER TABLE cto_signals ADD COLUMN IF NOT EXISTS volume_6h REAL;
ALTER TABLE cto_signals ADD COLUMN IF NOT EXISTS volume_24h REAL;
ALTER TABLE wallet_payments ADD COLUMN IF NOT EXISTS liquidity_usd REAL;
ALTER TABLE wallet_payments ADD COLUMN IF NOT EXISTS volume_5m REAL;
ALTER TABLE wallet_payments ADD COLUMN IF NOT EXISTS volume_1h REAL;
ALTER TABLE wallet_payments ADD COLUMN IF NOT EXISTS volume_6h REAL;
ALTER TABLE wallet_payments ADD COLUMN IF NOT EXISTS volume_24h REAL;

-- Post-Signal 1h & 4h OHLCV Peak, Min, Pre-Peak Drawdown, and Trajectory Columns
ALTER TABLE wallet_payments
  ADD COLUMN IF NOT EXISTS max_mc_1h REAL,
  ADD COLUMN IF NOT EXISTS peak_mult_1h REAL,
  ADD COLUMN IF NOT EXISTS min_mc_1h REAL,
  ADD COLUMN IF NOT EXISTS min_dd_1h_pct REAL,
  ADD COLUMN IF NOT EXISTS pre_peak_low_mc_1h REAL,
  ADD COLUMN IF NOT EXISTS pre_peak_dd_1h_pct REAL,
  ADD COLUMN IF NOT EXISTS path_1h TEXT,
  ADD COLUMN IF NOT EXISTS max_mc_4h REAL,
  ADD COLUMN IF NOT EXISTS peak_mult_4h REAL,
  ADD COLUMN IF NOT EXISTS min_mc_4h REAL,
  ADD COLUMN IF NOT EXISTS min_dd_4h_pct REAL,
  ADD COLUMN IF NOT EXISTS pre_peak_low_mc_4h REAL,
  ADD COLUMN IF NOT EXISTS pre_peak_dd_4h_pct REAL,
  ADD COLUMN IF NOT EXISTS path_4h TEXT,
  ADD COLUMN IF NOT EXISTS perf_checked_stage INTEGER DEFAULT 0,
  ADD COLUMN IF NOT EXISTS metrics_data JSONB;

ALTER TABLE dex_validated
  ADD COLUMN IF NOT EXISTS max_mc_1h REAL,
  ADD COLUMN IF NOT EXISTS peak_mult_1h REAL,
  ADD COLUMN IF NOT EXISTS min_mc_1h REAL,
  ADD COLUMN IF NOT EXISTS min_dd_1h_pct REAL,
  ADD COLUMN IF NOT EXISTS pre_peak_low_mc_1h REAL,
  ADD COLUMN IF NOT EXISTS pre_peak_dd_1h_pct REAL,
  ADD COLUMN IF NOT EXISTS path_1h TEXT,
  ADD COLUMN IF NOT EXISTS max_mc_4h REAL,
  ADD COLUMN IF NOT EXISTS peak_mult_4h REAL,
  ADD COLUMN IF NOT EXISTS min_mc_4h REAL,
  ADD COLUMN IF NOT EXISTS min_dd_4h_pct REAL,
  ADD COLUMN IF NOT EXISTS pre_peak_low_mc_4h REAL,
  ADD COLUMN IF NOT EXISTS pre_peak_dd_4h_pct REAL,
  ADD COLUMN IF NOT EXISTS path_4h TEXT,
  ADD COLUMN IF NOT EXISTS perf_checked_stage INTEGER DEFAULT 0,
  ADD COLUMN IF NOT EXISTS metrics_data JSONB;

-- Enable Row Level Security (RLS)
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE workflows ENABLE ROW LEVEL SECURITY;
ALTER TABLE rules ENABLE ROW LEVEL SECURITY;
ALTER TABLE cto_signals ENABLE ROW LEVEL SECURITY;
ALTER TABLE dex_validated ENABLE ROW LEVEL SECURITY;
ALTER TABLE wallet_payments ENABLE ROW LEVEL SECURITY;

-- Backend-only access. The application uses a server-side Supabase secret key,
-- which assumes the service_role and bypasses RLS. Public and normal signed-in
-- clients must not access these operational tables directly.
DROP POLICY IF EXISTS "Allow all operations on settings" ON settings;
DROP POLICY IF EXISTS "Allow all operations on workflows" ON workflows;
DROP POLICY IF EXISTS "Allow all operations on rules" ON rules;
DROP POLICY IF EXISTS "Allow all operations on cto_signals" ON cto_signals;
DROP POLICY IF EXISTS "Allow all operations on dex_validated" ON dex_validated;
DROP POLICY IF EXISTS "Allow all operations on wallet_payments" ON wallet_payments;

REVOKE ALL ON TABLE settings, workflows, rules, cto_signals, dex_validated, wallet_payments
FROM anon, authenticated;

REVOKE ALL ON SEQUENCE workflows_id_seq, rules_id_seq,
    cto_signals_id_seq, dex_validated_id_seq, wallet_payments_id_seq
FROM anon, authenticated;
